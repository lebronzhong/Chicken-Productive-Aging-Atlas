#!/usr/bin/env python3
import argparse
import os
import sys
import numpy as np
import pandas as pd
from tensorqtl import post


def main():
    parser = argparse.ArgumentParser(
        description="TensorQTL official-style FDR calculation using post.calculate_qvalues"
    )
    parser.add_argument("input", help="Input TensorQTL cis permutation result: *.cis_qtl.txt.gz")
    parser.add_argument("output", help="Output table: *.cis_qtl.txt")
    parser.add_argument("fdr", type=float, help="FDR cutoff, e.g. 0.05")
    args = parser.parse_args()

    if not os.path.exists(args.input):
        sys.exit(f"[ERROR] Input not found: {args.input}")

    print(f"[INFO] Reading: {args.input}", flush=True)
    res_df = pd.read_csv(args.input, sep="\t")

    required = {"pval_beta", "pval_nominal", "beta_shape1", "beta_shape2"}
    missing = required - set(res_df.columns)
    if missing:
        sys.exit(f"[ERROR] Missing required columns: {missing}")

    for col in ["pval_beta", "pval_nominal", "beta_shape1", "beta_shape2"]:
        res_df[col] = pd.to_numeric(res_df[col], errors="coerce")

    print(f"[INFO] Phenotypes: {res_df.shape[0]}", flush=True)
    print(f"[INFO] Calculating q-values and nominal thresholds, FDR={args.fdr}", flush=True)

    # Different TensorQTL versions behave differently:
    # some return a DataFrame, while others modify res_df in place and return None.
    ret = post.calculate_qvalues(res_df, fdr=args.fdr)

    if ret is not None:
        res_df = ret

    if res_df is None:
        sys.exit("[ERROR] post.calculate_qvalues returned None and res_df was lost")

    if "qval" not in res_df.columns:
        sys.exit("[ERROR] qval was not generated by tensorqtl.post.calculate_qvalues")

    if "pval_nominal_threshold" not in res_df.columns:
        sys.exit(
            "[ERROR] pval_nominal_threshold was not generated by tensorqtl.post.calculate_qvalues"
        )

    sig = res_df["qval"] <= args.fdr

    # Use TRUE/FALSE strings to match the original R-style output and downstream awk logic.
    res_df["is_eGene"] = np.where(sig, "TRUE", "FALSE")

    if "significant" in res_df.columns:
        res_df["significant"] = np.where(res_df["significant"].astype(bool), "TRUE", "FALSE")

    print(f"[INFO] Significant phenotypes: {int(sig.sum())}", flush=True)
    print(f"[INFO] Writing: {args.output}", flush=True)

    res_df.to_csv(args.output, sep="\t", index=False)
    print("[DONE]", flush=True)


if __name__ == "__main__":
    main()
